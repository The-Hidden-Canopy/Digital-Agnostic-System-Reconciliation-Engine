class ScanCancelled(Exception):
    """The caller stopped the scan; nothing from it was published."""


@dataclass(frozen=True)
class ScanLimits:
    """Bounds for one scan. The defaults keep the small bounded map used by the browser workbench."""
    max_files: int = field(default_factory=lambda: MAX_FILES)
    max_nodes: int = field(default_factory=lambda: MAX_NODES)
    max_directories: int = field(default_factory=lambda: MAX_DIRECTORIES)
    max_file_bytes: int = field(default_factory=lambda: MAX_FILE_BYTES)
    max_edges: int = field(default_factory=lambda: MAX_EDGES)
    max_preview_chars: int = field(default_factory=lambda: MAX_PREVIEW_CHARS)
    max_preview_lines: int = field(default_factory=lambda: MAX_PREVIEW_LINES)
    max_context_chars: int = field(default_factory=lambda: MAX_CONTEXT_CHARS)
    max_context_lines_per_file: int = field(default_factory=lambda: MAX_CONTEXT_LINES_PER_FILE)
    max_mapped_calls: int = field(default_factory=lambda: MAX_MAPPED_CALLS)
    max_warnings: int = field(default_factory=lambda: MAX_WARNINGS)
    workers: int = 0                    # 0: one isolated process per file
    skip_directories: frozenset = frozenset(SKIP)
    detect_build_trees: bool = False    # skip folders that contain a build-tree or virtual-environment marker
    skip_generated: bool = False        # list generated or minified files without parsing them
    list_unparsed_files: bool = False   # keep unreadable, oversized and generated files visible as items
    compact_records: bool = False       # in-process only: slotted call records and shared strings

    @classmethod
    def desktop(cls, *, include_vendored=False, include_generated=False):
        """Bounds sized for a whole repository in the native desktop application."""
        from .repository_workers import default_worker_count
        return cls(max_files=20_000, max_nodes=600_000, max_directories=150_000, max_file_bytes=2_000_000,
                   # Captured excerpts are only the fallback for files that change after the scan;
                   # an unchanged file is shown whole from disk once its bytes are checked against the scan.
                   max_edges=2_000_000, max_preview_chars=3_000_000, max_preview_lines=40,
                   max_context_chars=6_000_000, max_context_lines_per_file=60, max_mapped_calls=20_000,
                   max_warnings=400, workers=default_worker_count(),
                   skip_directories=frozenset(SKIP if include_vendored else VENDOR_OR_BUILD),
                   detect_build_trees=not include_vendored, skip_generated=not include_generated,
                   list_unparsed_files=True, compact_records=True)


def _link(path):
    try:
        s = path.lstat()
        return path.is_symlink() or bool(getattr(s, "st_file_attributes", 0) & 0x400)
    except OSError:
        return True


def _read_source(root: Path, relative: Path, limit: int | None = None) -> bytes:
    """Open beneath the selected root; refuse links in directory components where supported."""
    parts = relative.parts
    if not parts or any(part in ("", ".", "..") for part in parts):
        raise OSError("invalid relative source path")
    file_flags = os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0) | getattr(os, "O_NONBLOCK", 0) | getattr(os, "O_BINARY", 0)
    if os.open in os.supports_dir_fd and getattr(os, "O_NOFOLLOW", 0) and getattr(os, "O_DIRECTORY", 0):
        directory_flags = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW
        directory_fd = os.open(root.anchor, directory_flags)
        try:
            for part in (*root.parts[1:], *parts[:-1]):
                next_fd = os.open(part, directory_flags, dir_fd=directory_fd)
                os.close(directory_fd)
                directory_fd = next_fd
            fd = os.open(parts[-1], file_flags, dir_fd=directory_fd)
        finally:
            os.close(directory_fd)
    else:
        current = root
        for part in parts:
            current = current / part
            if _link(current):
                raise OSError("link or reparse point is not a source file")
        fd = os.open(current, file_flags)
    with os.fdopen(fd, "rb") as source:
        if not stat.S_ISREG(os.fstat(source.fileno()).st_mode):
            raise OSError("source is not a regular file")
        return source.read((MAX_FILE_BYTES if limit is None else limit) + 1)


def normalize_source(raw: bytes):
    """Return (utf-8 bytes, note) for text, or (None, reason) for content that is not source text.

    Parsers and excerpts use the normalized bytes; the recorded SHA-256 is always of the file's own bytes.
    """
    if raw.startswith((b"\xff\xfe", b"\xfe\xff")):
        try:
            return raw.decode("utf-16").encode("utf-8"), "decoded from UTF-16"
        except UnicodeError:
            return None, "not readable as UTF-16 text"
    if b"\x00" in raw[:8192]:
        return None, "binary content"
    try:
        raw.decode("utf-8-sig")
        return raw, None
    except UnicodeError:
        return raw.decode("cp1252", errors="replace").encode("utf-8"), "not valid UTF-8; shown as Windows-1252, so some characters may be wrong"


def looks_generated(name: str, raw: bytes):
    """Reason a file is treated as generated or minified, or None."""
    lowered = name.lower()
    if lowered.endswith(GENERATED_SUFFIXES):
        return "generated-file name"
    head = raw[:2048]
    if any(marker in head for marker in GENERATED_MARKERS):
        return "generated-file header"
    if len(raw) > 20_000 and raw.count(b"\n") < len(raw) / 2000:
        return "very long lines (minified or data)"
    return None


def _module(path):
    parts = list(PurePosixPath(path).with_suffix("").parts)
    if parts[-1] == "__init__":
        parts.pop()
    return ".".join(parts)


def _import_module(path, module, level):
    if not level:
        return module
    parts = _module(path).split(".") if _module(path) else []
    if not path.endswith("/__init__.py") and path != "__init__.py":
        parts = parts[:-1]
    if level - 1 > len(parts):
        return None
    prefix = parts[:len(parts) - (level - 1)]
    return ".".join(prefix + ([module] if module else []))


class _Coverage:
    """Counts and a few examples for everything the scan saw but did not turn into a parsed file."""

    def __init__(self, limits: ScanLimits):
        self.limits = limits
        self.warnings, self.suppressed = [], 0
        self.skipped = {}
        self.unsupported = Counter()
        self.found, self.parsed, self.partial, self.failed = Counter(), Counter(), Counter(), Counter()
        self.top = {}
        self.nested = []
        self.lock = threading.Lock()

    def warn(self, message):
        with self.lock:
            if len(self.warnings) < self.limits.max_warnings:
                self.warnings.append(message)
            else:
                self.suppressed += 1

    def skip(self, category, example, message=None):
        with self.lock:
            entry = self.skipped.setdefault(category, {"count": 0, "examples": []})
            entry["count"] += 1
            if len(entry["examples"]) < MAX_EXAMPLES:
                entry["examples"].append(example)
        if message:
            self.warn(message)

    def top_level(self, rel, inspected):
        name = rel.split("/", 1)[0] if "/" in rel else "(files in the selected folder)"
        entry = self.top.setdefault(name, [0, 0])
        entry[0] += 1
        entry[1] += int(inspected)


def _walk(root: Path, limits: ScanLimits, cover: _Coverage, cancelled, progress):
    """Collect supported files in a stable order and account for everything that is passed over."""
    candidates, total, directories, complete = [], 0, 0, True

    def walk_error(error):
        cover.skip("unreadable_directory", str(error.filename or "unknown"),
                   "Could not inspect a directory: " + str(error.filename or "unknown"))
    for directory, dirs, names in os.walk(root, followlinks=False, onerror=walk_error):
        directories += 1
        if directories > limits.max_directories:
            complete = False
            if total <= limits.max_files:
                cover.warn(f"Directory limit reached ({limits.max_directories}).")
            break
        if cancelled():
            raise ScanCancelled()
        base = Path(directory)
        prefix = base.relative_to(root).as_posix()
        prefix = "" if prefix == "." else prefix + "/"
        kept = []
        for name in sorted(dirs):
            rel = prefix + name
            if name.startswith("."):
                cover.skip("hidden_directory", rel)
            elif name == "__pycache__":
                cover.skip("bytecode_cache_directory", rel)  # counted apart so it does not crowd out real examples
            elif name in limits.skip_directories or (limits.detect_build_trees and name.startswith("cmake-build")):
                cover.skip("vendor_or_build_directory", rel)
            elif _link(base / name):
                cover.skip("linked_directory", rel)
            elif limits.detect_build_trees and any((base / name / marker).is_file() for marker in BUILD_TREE_MARKERS):
                cover.skip("vendor_or_build_directory", rel)
            else:
                kept.append(name)
                if limits.list_unparsed_files and len(cover.nested) < 500 and (base / name / ".git").exists():
                    cover.nested.append(rel)
        dirs[:] = kept
        for name in sorted(names):
            if name.startswith("."):
                cover.skip("hidden_file", prefix + name)
                continue
            suffix = os.path.splitext(name)[1]
            language = LANGUAGES.get(suffix) or LANGUAGES.get(suffix.lower())
            if not language:
                cover.unsupported[suffix.lower() or "(no extension)"] += 1
                continue
            rel = prefix + name
            if total >= limits.max_files:
                total += 1  # counted, not inspected
                cover.found[language] += 1
                cover.top_level(rel, False)
                continue
            if _link(base / name):
                cover.skip("linked_file", rel)
                continue
            total += 1
            cover.found[language] += 1
            cover.top_level(rel, True)
            candidates.append((rel, language))
        if progress and directories % 200 == 0:
            progress("Looking through folders", len(candidates), None, prefix.rstrip("/"))
    if total > limits.max_files:
        cover.warn(f"File limit reached: only the first {limits.max_files} supported source files were inspected.")
    return candidates, total, complete


def _excerpts(text: str, parsed: dict, limits: ScanLimits):
    lines = text.splitlines()
    # [line number, text, shortened]: expanded to a dictionary only for files inside the scan-wide excerpt budget
    preview = [[number, line[:MAX_PREVIEW_LINE_CHARS], len(line) > MAX_PREVIEW_LINE_CHARS]
               for number, line in enumerate(lines[:limits.max_preview_lines], 1)]
    captured = len(preview)
    evidence_points = [line for node in parsed["nodes"] for line in (node.get("shape") or {}).get("evidence_lines", [])]
    points = sorted({item.get("line") for item in parsed["nodes"] + parsed["calls"] + evidence_points
                     if type(item.get("line")) is int and 1 <= item["line"] <= len(lines)})
    wanted = sorted({line for point in points for line in range(max(1, point - CONTEXT_RADIUS), min(len(lines), point + CONTEXT_RADIUS) + 1)
                     if line > captured})
    context = [[number, lines[number - 1][:MAX_PREVIEW_LINE_CHARS], len(lines[number - 1]) > MAX_PREVIEW_LINE_CHARS]
               for number in wanted[:limits.max_context_lines_per_file]]
    return {"line_count": len(lines), "preview": preview, "context": context, "context_wanted": len(wanted)}


def _inspect_file(root: Path, rel: str, language: str, limits: ScanLimits, worker_limits: Limits, worker, cache):
    """Read, classify and parse one file. Returns a record; never raises for a problem with the file itself."""
    record = {"path": rel, "language": language, "status": "parsed"}
    try:
        raw = _read_source(root, Path(*rel.split("/")), limits.max_file_bytes)
    except OSError:
        return {**record, "status": "unreadable", "reason": "could not be read"}
    record["size"] = len(raw)
    if len(raw) > limits.max_file_bytes:
        return {**record, "status": "oversized", "reason": f"larger than the {limits.max_file_bytes:,}-byte limit"}
    digest = hashlib.sha256(raw).hexdigest()
    record["digest"] = digest
    if limits.skip_generated:
        reason = looks_generated(rel.rsplit("/", 1)[-1], raw)
        if reason:
            return {**record, "status": "generated", "reason": reason}
    data, note = normalize_source(raw)
    if data is None:
        return {**record, "status": "binary", "reason": note}
    if note:
        record["note"] = note
    key = None
    if cache is not None:
        from .repository_cache import record_key
        key = record_key(rel, digest, language, f"{limits.max_preview_lines}:{limits.max_context_lines_per_file}")
        cached = cache.get(key)
        if cached is not None and cached.get("status") == "parsed" and "parsed" in cached:
            cached.update(path=rel, language=language, digest=digest, cache_key=key, from_cache=True)
            for node in cached["parsed"]["nodes"]:
                node["sha256"], node["path"] = digest, rel
            if limits.compact_records:
                from .repository_records import compact_parsed
                compact_parsed(cached["parsed"], rel)
            return cached
    try:
        if worker is not None:
            parsed = worker.parse("repository-" + language, data, rel)
        else:
            parsed = extract_isolated("repository-" + language, data, rel, worker_limits)
    except ExtractionFailure as exc:
        if exc.code == "isolation_unavailable":
            raise
        return {**record, "status": "failed", "reason": exc.code}
    except Exception as exc:  # WorkerFailure from the pool
        return {**record, "status": "failed", "reason": getattr(exc, "code", type(exc).__name__)}
    if parsed.get("error"):
        return {**record, "status": "failed", "reason": parsed["error"]}
    for node in parsed["nodes"]:
        node["sha256"], node["path"] = digest, rel  # one shared string per file; digest is of the file's own bytes
    record.update(_excerpts(data.decode("utf-8-sig"), parsed, limits))
    record["parsed"] = parsed
    if key is not None:
        cache.put(key, record)
        record["cache_key"] = key
    if limits.compact_records:
        from .repository_records import compact_parsed
        compact_parsed(parsed, rel)
    return record


def _inspect_all(root, candidates, limits, worker_limits, cache, cancelled, progress):
    records = [None] * len(candidates)
    state = {"next": 0, "done": 0, "error": None, "reported": 0.0}
    lock = threading.Lock()

    def run(worker):
        try:
            while True:
                with lock:
                    index = state["next"]
                    if index >= len(candidates) or state["error"] is not None:
                        return
                    state["next"] += 1
                if cancelled():
                    raise ScanCancelled()
                rel, language = candidates[index]
                records[index] = _inspect_file(root, rel, language, limits, worker_limits, worker, cache)
                with lock:
                    state["done"] += 1
                    now = time.monotonic()
                    report = progress is not None and now - state["reported"] >= 0.1
                    if report:
                        state["reported"] = now
                        done = state["done"]
                if report:
                    progress("Reading source", done, len(candidates), rel)
        except BaseException as exc:  # carried to the caller; includes cancellation
            with lock:
                if state["error"] is None:
                    state["error"] = exc
        finally:
            if worker is not None:
                worker.close()

    count = min(limits.workers, max(1, len(candidates))) if worker_limits.isolation == "portable" else 0
    if count > 0:
        from .repository_workers import ParserWorker
        threads = [threading.Thread(target=run, args=(ParserWorker(worker_limits),), daemon=True) for _ in range(count)]
        for thread in threads:
            thread.start()
        for thread in threads:
            thread.join()
    else:
        run(None)
    if state["error"] is not None:
        raise state["error"]
    return records


def scan_repository(path: str, *, limits: Limits | None = None, scan_limits: ScanLimits | None = None,
                    progress=None, should_cancel=None, cache=None) -> dict:
    limits = limits or Limits()
    sl = scan_limits or ScanLimits()
    cancelled = should_cancel or (lambda: False)
    if path.startswith(("\\\\", "//")):
        raise ValueError("Network paths are not supported")
    candidate = Path(path).expanduser().absolute()
    if os.name == "nt" and candidate.drive:
        import ctypes
        if ctypes.windll.kernel32.GetDriveTypeW(str(candidate.anchor)) == 4:
            raise ValueError("Network drives are not supported")
    root = candidate.resolve(strict=True)
    if os.name == "nt" and root.drive and ctypes.windll.kernel32.GetDriveTypeW(str(root.anchor)) == 4:
        raise ValueError("Network drives are not supported")
    if not root.is_dir():
        raise ValueError("Choose a directory containing the repository")
    repo_id = hashlib.sha256(os.fsencode(str(root))).hexdigest()
    started = time.monotonic()
    cover = _Coverage(sl)
    warnings = cover.warnings
    nodes = [{"id": "repo", "kind": "repository", "name": root.name, "path": "", "evidence": "static"}]
    edges, files = [], []
    candidates, found_total, walk_complete = _walk(root, sl, cover, cancelled, progress)
    walked = time.monotonic()
    records = _inspect_all(root, candidates, sl, limits, cache, cancelled, progress)
    inspected = time.monotonic()
    if progress:
        progress("Linking definitions and calls", len(candidates), len(candidates), "")
    preview_budget, context_budget = sl.max_preview_chars, sl.max_context_chars
    digests, cache_keys, node_limit_reached = defaultdict(list), [], False
    for record in records:
        rel, language = record["path"], record["language"]
        status = record["status"]
        if status != "parsed":
            reason = record.get("reason") or status
            cover.failed[language] += 1
            message = {"unreadable": f"Could not read: {rel}", "oversized": f"Skipped oversized file: {rel}",
                       "generated": f"Listed without parsing (generated or minified): {rel}",
                       "binary": f"Skipped non-text content: {rel}"}.get(status, f"Could not parse {rel}: {reason}")
            cover.skip({"failed": "could_not_parse"}.get(status, status), rel, message)
            if sl.list_unparsed_files and len(nodes) < sl.max_nodes - 1:
                nodes.append({"id": "file:" + rel, "kind": "file", "name": rel, "path": rel, "sha256": record.get("digest"),
                              "fingerprint": record.get("digest"), "language": language, "evidence": "static",
                              "source_preview": [], "source_preview_truncated": False, "source_context": [],
                              "source_context_truncated": False, "parse_status": status,
                              "parse_note": "Listed but not parsed: " + reason + "."})
                edges.append({"source": "repo", "target": "file:" + rel, "kind": "contains", "evidence": "static"})
            continue
        if len(nodes) >= sl.max_nodes - 1:
            if not node_limit_reached:
                warnings.append(f"Node limit reached ({sl.max_nodes}); remaining files were not inspected.")
                node_limit_reached = True
            cover.skip("node_limit", rel)
            continue
        parsed = record["parsed"]
        if parsed.get("partial"):
            cover.partial[language] += 1
            cover.skip("partial_syntax", rel, f"Partial syntax coverage in {rel}: error regions and affected declarations were skipped.")
        if record.get("note"):
            cover.skip("encoding", rel, f"Text encoding in {rel}: {record['note']}.")
        fid, digest = "file:" + rel, record["digest"]
        if record.get("cache_key"):
            cache_keys.append(record["cache_key"])
        digests[digest].append(rel)
        preview = []
        for number, text, shortened in record["preview"]:
            if preview_budget <= 0:
                break
            available = min(MAX_PREVIEW_LINE_CHARS, max(0, preview_budget - 1))
            preview.append({"line": number, "text": text[:available], "truncated": shortened or len(text) > available})
            preview_budget -= len(preview[-1]["text"]) + 1
        context = []
        for number, text, shortened in record["context"]:
            if context_budget <= 0:
                break
            available = min(MAX_PREVIEW_LINE_CHARS, max(0, context_budget - 1))
            context.append({"line": number, "text": text[:available], "truncated": shortened or len(text) > available})
            context_budget -= len(context[-1]["text"]) + 1
        record["preview"] = record["context"] = None  # the scan keeps only what fitted the budget
        node = {"id": fid, "kind": "file", "name": rel, "path": rel, "sha256": digest,
                "fingerprint": digest, "language": language, "evidence": "static", "source_preview": preview,
                "source_preview_truncated": len(preview) < record["line_count"] or any(line["truncated"] for line in preview),
                "source_context": context,
                "source_context_truncated": len(context) < record["context_wanted"] or any(line["truncated"] for line in context)}
        if record.get("note"):
            node["parse_note"] = "Text encoding: " + record["note"] + "."
        if parsed.get("partial"):
            node["parse_note"] = (node.get("parse_note", "") + " Partial syntax coverage: error regions and affected declarations were skipped.").strip()
        nodes.append(node)
        edges.append({"source": "repo", "target": fid, "kind": "contains", "evidence": "static"})
        selected = parsed["nodes"][:sl.max_nodes - len(nodes)]
        if parsed.get("truncated") or len(selected) != len(parsed["nodes"]):
            cover.skip("item_limit_in_file", rel, f"Node or call limit reached in {rel}.")
        ids = {n["id"] for n in selected} | {fid}
        nodes.extend(selected)
        edges.extend(e for e in parsed["edges"] if e["source"] in ids and e["target"] in ids)
        cover.parsed[language] += 1
        files.append({"path": rel, "fid": fid, "parsed": parsed, "ids": ids, "digest": digest, "language": language})
    node_by_id = {node["id"]: node for node in nodes}
    for node in nodes:
        if node["kind"] in ("function", "file"):
            node["call_sites"] = []
            node["call_sites_truncated"] = False

    def fits(call, target):
        """False when the written argument count cannot fit the candidate's parameters."""
        arity = (node_by_id[target].get("shape") or {}).get("arity")
        count = call.get("written_arguments")
        if not arity or type(count) is not int or call.get("expands"):
            return True
        # Type::method(receiver, ...) writes the receiver as an argument; receiver.method(...) does not.
        for offset in ((1,) if arity.get("self") and "::" in call.get("written", "") else (0,)):
            if arity["min"] + offset <= count and (arity["max"] is None or count <= arity["max"] + offset):
                return True
        return False

    from .repository_records import CallRecord

    def link_call(file, call, target, basis, form=None):
        """Record the written call (static) and, when a rule chose one, its candidate target (inferred)."""
        caller = node_by_id.get(call["caller"])
        if not caller:
            return
        if target and not fits(call, target):
            target, basis, form = None, None, "arity"
        if target:
            edge = {"source": call["caller"], "target": target, "kind": "possible call",
                    "evidence": "inferred", "path": file["path"], "line": call["line"], "written": call["written"],
                    "snippet": call["snippet"], "sha256": file["digest"], "basis": basis}
            if call.get("snippet_truncated") or not sl.compact_records:
                edge["snippet_truncated"] = call.get("snippet_truncated", False)
            edges.append(edge)
        if len(caller["call_sites"]) >= 30:
            caller["call_sites_truncated"] = True
            return
        unresolved = None if target else form or ("complex" if not (call.get("base") or call.get("member") or call.get("scope")) else
                                                   "member" if (call.get("attribute") or call.get("member")) else "name")
        if sl.compact_records:
            caller["call_sites"].append(CallRecord.site(call, file["path"], file["digest"], target, basis, unresolved))
            return
        caller["call_sites"].append({"written": call["written"], "written_truncated": call.get("written_truncated", False), "written_arguments": call.get("written_arguments"),
            "path": file["path"], "line": call["line"], "snippet": call["snippet"], "snippet_truncated": call.get("snippet_truncated", False), "line_sha256": call["line_sha256"], "sha256": file["digest"],
            "evidence": "static", "resolution": "inferred" if target else "unresolved", "target_id": target, "basis": basis, "unresolved_form": unresolved})

    def module_edge(file, imp, target, basis=None):
        edge = {"source": imp["id"], "target": target["fid"], "kind": "possible local module",
                "evidence": "inferred", "path": file["path"], "line": imp["line"],
                "snippet": imp["snippet"], "sha256": file["digest"]}
        if basis:
            edge["basis"] = basis
        edges.append(edge)

    LOCAL_BASIS = "a function of this name is defined inside the enclosing function; conditional redefinition is not resolved"

    def local_call(file, call):
        """A call to a name bound inside the enclosing function is settled here and never matched elsewhere."""
        if call.get("local_target"):
            known = call["local_target"] in file["ids"] and node_by_id.get(call["local_target"], {}).get("kind") == "function"
            link_call(file, call, call["local_target"] if known else None, LOCAL_BASIS if known else None, None if known else "local")
            return True
        if call.get("local"):
            link_call(file, call, None, None, "local")
            return True
        return False

    def same_class(file, call):
        """A call written on self/this, or a bare name inside a member body, against this file's members of that type."""
        if not call.get("member_of"):
            return None
        matches = file["parsed"].get("members", {}).get(call["member_of"], {}).get(call["member"], [])
        return matches[0] if len(matches) == 1 and matches[0] in file["ids"] else None

    MEMBER_BASIS = "unique member name defined for the same type in this file; inheritance, overriding, overloads and dynamic dispatch are not resolved"

    # ---------------------------------------------------------------- Python
    modules, suffixes = defaultdict(list), defaultdict(list)
    for f in files:
        if f["language"] == "python":
            name = _module(f["path"])
            modules[name].append(f)
            parts = name.split(".")
            for start in range(1, len(parts)):
                suffixes[".".join(parts[start:])].append(f)

    standard_library = getattr(__import__("sys"), "stdlib_module_names", frozenset())

    def unique_module(name, importer=None):
        """(file, approximate): an exact module path from the scan root, else a unique path-suffix match.

        A suffix match is only a guess about the import path, so it is refused for standard-library
        names, and a single-segment name must be a sibling of the importing file.
        """
        options = modules.get(name, [])
        if len(options) == 1:
            return options[0], False
        if options or not name or name.split(".", 1)[0] in standard_library:
            return None, False
        near = suffixes.get(name, [])
        if len(near) != 1:
            return None, False
        if "." not in name and (importer is None or posixpath.dirname(near[0]["path"]) != posixpath.dirname(importer)):
            return None, False
        return near[0], True

    SUFFIX_BASIS = "module name matches the end of exactly one scanned file path; the import path used at run time was not checked"
    for f in files:
        if f["language"] != "python":
            continue
        parsed, ids = f["parsed"], f["ids"]
        bindings = defaultdict(list)
        for imp in parsed["imports"]:
            module = _import_module(f["path"], imp["module"], imp["level"])
            target, approximate = unique_module(module, f["path"]) if module is not None else (None, False)
            submodule, sub_approximate = (None, False)
            if module is not None and imp["symbol"] and imp["symbol"] != "*":
                submodule, sub_approximate = unique_module((module + "." if module else "") + imp["symbol"], f["path"])
            if imp["id"] in ids:
                if submodule:
                    module_edge(f, imp, submodule, SUFFIX_BASIS if sub_approximate else None)
                elif target:
                    module_edge(f, imp, target, SUFFIX_BASIS if approximate else None)
            if imp["bound"]:
                bindings[imp["bound"]].append((imp, target, approximate, submodule, sub_approximate))
        for call in parsed["calls"]:
            if call["caller"] not in ids:
                continue
            if local_call(f, call):
                continue
            target_id, basis = None, None
            if call["base"] in bindings:
                choices = bindings[call["base"]]
                if len(choices) == 1:
                    imp, target, approximate, submodule, sub_approximate = choices[0]
                    symbol = imp["symbol"] if imp["symbol"] and not call["attribute"] else call["attribute"]
                    # Dotted imports without an explicit alias bind the package, not the final module.
                    if target and symbol and not (imp["symbol"] and call["attribute"]) and (imp["symbol"] or imp["module"] == imp["bound"] or imp["aliased"]):
                        matches = target["parsed"]["top_level"].get(symbol, [])
                        if len(matches) == 1 and matches[0] in target["ids"]:
                            target_id = matches[0]
                            basis = "unique import and name match; rebinding and runtime dispatch are not resolved"
                            if approximate:
                                basis += "; " + SUFFIX_BASIS
                    elif submodule and imp["symbol"] and call["attribute"]:
                        # from package import module; module.function()
                        matches = submodule["parsed"]["top_level"].get(call["attribute"], [])
                        if len(matches) == 1 and matches[0] in submodule["ids"]:
                            target_id = matches[0]
                            basis = "unique imported-module and name match; rebinding and runtime dispatch are not resolved"
                            if sub_approximate:
                                basis += "; " + SUFFIX_BASIS
            elif call.get("member_of"):
                target_id = same_class(f, call)
                basis = MEMBER_BASIS if target_id else None
            elif not call["attribute"]:
                matches = parsed["top_level"].get(call["base"], [])
                if len(matches) == 1 and matches[0] in ids:
                    target_id = matches[0]
                    basis = "unique same-file name match; shadowing and runtime dispatch are not resolved"
            link_call(f, call, target_id, basis)

    # ---------------------------------------------------------------- JavaScript and TypeScript
    js_files = {f["path"]: f for f in files if f["language"] in JS_FAMILY}

    def js_target(path, source):
        if not source.startswith(("./", "../")):
            return None
        stem = posixpath.normpath(posixpath.join(posixpath.dirname(path), source))
        if stem == ".." or stem.startswith("../"):
            return None
        endings = (".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs")
        choices = [stem] if PurePosixPath(stem).suffix in endings + (".mts", ".cts") else [stem + x for x in endings] + [stem + "/index" + x for x in endings]
        matches = [js_files[x] for x in choices if x in js_files]
        return matches[0] if len(matches) == 1 else None
    for f in js_files.values():
        parsed, ids = f["parsed"], f["ids"]
        bindings = defaultdict(list)
        linked_imports = set()
        for imp in parsed["imports"]:
            target = js_target(f["path"], imp["source"])
            if target and imp["id"] in ids and imp["id"] not in linked_imports:
                module_edge(f, imp, target)
                linked_imports.add(imp["id"])
            if imp["bound"]:
                bindings[imp["bound"]].append((imp, target))
        for call in parsed["calls"]:
            if call["caller"] not in ids:
                continue
            if local_call(f, call):
                continue
            target_id, basis = None, None
            if call["base"] in bindings and len(bindings[call["base"]]) == 1:
                imp, target = bindings[call["base"]][0]
                symbol = call["attribute"] if imp["namespace"] and call["attribute"] else imp["symbol"] if not call["attribute"] else None
                if imp.get("commonjs") and imp["namespace"] and not call["attribute"]:
                    symbol = "default"  # const run = require("./run"); run()
                matches = target["parsed"]["exports"].get(symbol, []) if target and symbol else []
                if len(matches) == 1 and matches[0] in target["ids"]:
                    target_id = matches[0]
                    basis = "unique import and export name match; rebinding and runtime loading are not resolved"
            elif call.get("member_of"):
                target_id = same_class(f, call)
                basis = MEMBER_BASIS if target_id else None
            elif call["base"] not in bindings and not call["attribute"]:
                matches = parsed["top_level"].get(call["base"], [])
                if len(matches) == 1 and matches[0] in ids:
                    target_id = matches[0]
                    basis = "unique same-file name match; shadowing and runtime dispatch are not resolved"
            link_call(f, call, target_id, basis)

    # ---------------------------------------------------------------- C and C++
    cpp_files = {f["path"]: f for f in files if f["language"] in C_FAMILY}
    cpp_definitions, cpp_qualified, cpp_members, cpp_suffix = defaultdict(list), defaultdict(list), defaultdict(list), defaultdict(list)
    cpp_linkable = defaultdict(list)  # definitions another file could name: not static, not in an unnamed namespace
    for f in cpp_files.values():
        for name, found in f["parsed"]["top_level"].items():
            cpp_definitions[name].extend((f, node_id) for node_id in found if node_id in f["ids"])
            cpp_linkable[name].extend(node_id for node_id in found if node_id in f["ids"] and not node_by_id[node_id].get("file_local"))
        for name, found in f["parsed"].get("qualified", {}).items():
            parts = name.split(".")
            for start in range(len(parts) - 1):
                cpp_qualified[".".join(parts[start:])].extend(node_id for node_id in found if node_id in f["ids"])
        for owner, methods in f["parsed"].get("members", {}).items():
            parts = owner.split(".")
            for method, found in methods.items():
                for start in range(len(parts)):
                    cpp_members[".".join(parts[start:]) + "." + method].extend(node_id for node_id in found if node_id in f["ids"])
        parts = f["path"].split("/")
        for start in range(len(parts)):
            cpp_suffix["/".join(parts[start:])].append(f)
    INCLUDE_SUFFIX_BASIS = "the written path matches the end of exactly one scanned file path; include directories were not read"
    for f in cpp_files.values():
        parsed, ids = f["parsed"], f["ids"]
        for imp in parsed["imports"]:
            if imp["id"] not in ids:
                continue
            source = imp["source"].replace("\\", "/")
            target = cpp_files.get(posixpath.normpath(posixpath.join(posixpath.dirname(f["path"]), source))) if imp["local"] else None
            if target:
                module_edge(f, imp, target)
            elif (imp["local"] or "/" in source) and ".." not in source.split("/"):
                near = cpp_suffix.get(source.lstrip("./"), [])
                if len(near) == 1:
                    module_edge(f, imp, near[0], INCLUDE_SUFFIX_BASIS)
        for call in parsed["calls"]:
            if call["caller"] not in ids:
                continue
            if local_call(f, call):
                continue
            target_id, basis = same_class(f, call), None
            if target_id:
                basis = MEMBER_BASIS.replace("dynamic dispatch", "virtual dispatch") + "; macros are not expanded"
            elif call.get("scope"):
                written = call["scope"].replace("::", ".") + "." + call["attribute"]
                matches = cpp_members.get(written, []) or cpp_qualified.get(written, [])
                if len(matches) == 1:
                    target_id = matches[0]
                    basis = "unique qualified name across scanned files; overloads, templates, macros, compilation and linking are not resolved"
            elif not call["attribute"] and call["base"]:
                here = [node_id for node_id in parsed["top_level"].get(call["base"], ()) if node_id in ids]
                # A static or unnamed-namespace function in another file cannot be what this call names.
                visible = cpp_linkable.get(call["base"], ()) if not here else ()
                if len(here) == 1:
                    target_id = here[0]
                    basis = "unique name defined in this file; overloads, macros and templates are not resolved"
                elif not here and len(visible) == 1:
                    target_id = visible[0]
                    basis = "unique indexed name; compilation and linking are not resolved"
            link_call(f, call, target_id, basis)

    # ---------------------------------------------------------------- C#
    cs_files = [f for f in files if f["language"] == "csharp"]
    cs_types = defaultdict(list)
    for f in cs_files:
        for owner in f["parsed"].get("members", {}):
            cs_types[owner.rsplit(".", 1)[-1]].append((f, owner))
    for f in cs_files:
        parsed, ids = f["parsed"], f["ids"]
        for call in parsed["calls"]:
            if call["caller"] not in ids:
                continue
            if local_call(f, call):
                continue
            target_id, basis = same_class(f, call), None
            if target_id:
                basis = MEMBER_BASIS + "; partial types in other files and extension methods are not read"
            elif call["base"] and call["attribute"] and len(cs_types.get(call["base"], [])) == 1:
                owner_file, owner = cs_types[call["base"]][0]
                matches = owner_file["parsed"]["members"][owner].get(call["attribute"], [])
                if len(matches) == 1 and matches[0] in owner_file["ids"]:
                    target_id = matches[0]
                    basis = ("the written qualifier matches exactly one scanned type name and one member of it; the qualifier may "
                             "instead be a variable or property, and overloads, inheritance and extension methods are not resolved")
            elif call["base"] and not call["attribute"] and not call.get("member_of"):
                matches = parsed["top_level"].get(call["base"], [])
                if len(matches) == 1 and matches[0] in ids:
                    target_id = matches[0]
                    basis = "unique same-file name match; shadowing and runtime dispatch are not resolved"
            link_call(f, call, target_id, basis)

    # ---------------------------------------------------------------- Rust
    rust_files = {f["path"]: f for f in files if f["language"] == "rust"}

    def rust_context(path):
        """(crate source folder, module path) by the conventional layout; Cargo manifests are not read."""
        parts = path.split("/")
        if "src" in parts[:-1]:
            cut = len(parts) - 1 - parts[:-1][::-1].index("src")
            base, rest = "/".join(parts[:cut]), parts[cut:]
        else:
            base, rest = "/".join(parts[:-1]), parts[-1:]
        stem = rest[-1].rsplit(".", 1)[0]
        return base, rest[:-1] + ([] if stem in ("mod", "lib", "main") else [stem])

    def rust_module(base, module):
        stem = "/".join(([base] if base else []) + module)
        choices = [stem + ".rs", stem + "/mod.rs"] if module else [stem + "/lib.rs", stem + "/main.rs"]
        matches = [rust_files[x] for x in choices if x in rust_files]
        return matches[0] if len(matches) == 1 else None

    def rust_path(path, segments):
        """Absolute module path for written segments, or None when the form is not understood."""
        base, here = rust_context(path)
        if not segments:
            return base, None
        if segments[0] == "crate":
            return base, segments[1:]
        if segments[0] == "self":
            return base, here + segments[1:]
        if segments[0] == "super":
            current = list(here)
            while segments and segments[0] == "super":
                if not current:
                    return base, None
                current, segments = current[:-1], segments[1:]
            return base, current + segments
        return base, here + segments  # a child module; an external crate of that name simply finds no file
    RUST_BASIS = "unique module file and name match by conventional layout; Cargo manifests, re-exports, macros and trait dispatch are not resolved"
    for f in rust_files.values():
        parsed, ids = f["parsed"], f["ids"]
        bindings = defaultdict(list)
        for imp in parsed["imports"]:
            base, absolute = rust_path(f["path"], list(imp.get("segments") or []))
            module_target = function_target = None
            if absolute is not None and (not absolute or absolute[-1] != "*"):
                module_target = rust_module(base, absolute) if absolute else None
                if not module_target and absolute:
                    function_target = rust_module(base, absolute[:-1])
            elif absolute:
                module_target = rust_module(base, absolute[:-1])
            target = module_target or function_target
            if target and target is not f and imp["id"] in ids:
                module_edge(f, imp, target, "module path matches one scanned file by conventional layout; Cargo manifests were not read")
            if imp.get("bound") and target:
                bindings[imp["bound"]].append(("module", module_target, None) if module_target else ("item", function_target, absolute[-1]))
        for call in parsed["calls"]:
            if call["caller"] not in ids:
                continue
            if local_call(f, call):
                continue
            target_id, basis = same_class(f, call), None
            if target_id:
                basis = "unique method name for the same type in this file; trait dispatch, generics and impl blocks in other files are not resolved"
            elif call.get("scope"):
                scope = call["scope"].split("::")
                choices = bindings.get(scope[0], []) if len(scope) == 1 else []
                if len(scope) == 1 and len(parsed.get("members", {}).get(scope[0], {}).get(call["attribute"], [])) == 1:
                    target_id = parsed["members"][scope[0]][call["attribute"]][0]
                    basis = "unique associated function name for this type in this file; trait dispatch and other impl blocks are not resolved"
                else:
                    module_file = None
                    if len(choices) == 1 and choices[0][0] == "module":
                        module_file = choices[0][1]
                    elif not choices:
                        base, absolute = rust_path(f["path"], scope)
                        module_file = rust_module(base, absolute) if absolute else None
                    matches = module_file["parsed"]["top_level"].get(call["attribute"], []) if module_file else []
                    if len(matches) == 1 and matches[0] in module_file["ids"]:
                        target_id, basis = matches[0], RUST_BASIS
            elif call["base"] and not call["attribute"]:
                choices = bindings.get(call["base"], [])
                if len(choices) == 1 and choices[0][0] == "item":
                    matches = choices[0][1]["parsed"]["top_level"].get(choices[0][2], [])
                    if len(matches) == 1 and matches[0] in choices[0][1]["ids"]:
                        target_id, basis = matches[0], RUST_BASIS
                elif not choices:
                    matches = parsed["top_level"].get(call["base"], [])
                    if len(matches) == 1 and matches[0] in ids:
                        target_id = matches[0]
                        basis = "unique same-file name match; shadowing, macros and trait dispatch are not resolved"
            link_call(f, call, target_id, basis)

    # Add bounded, selectable written call sites after the file/function inventory.
    # The source node is static syntax; a target edge is still only an inference.
    mapped_calls, unmapped_calls = 0, 0
    for caller in list(nodes):
        for ordinal, call in enumerate(caller.get("call_sites", [])):
            needed_edges = 1 + int(bool(call["target_id"] and call["target_id"] in node_by_id))
            if mapped_calls >= sl.max_mapped_calls or len(nodes) >= sl.max_nodes or len(edges) + needed_edges > sl.max_edges:
                unmapped_calls += 1
                continue
            line_hash = call.get("line_sha256") or hashlib.sha256(call["snippet"].encode("utf-8")).hexdigest()
            fingerprint = hashlib.sha256((call["written"] + "\n" + line_hash).encode()).hexdigest()
            stable = hashlib.sha256((caller["id"] + "#" + str(call["line"]) + "#" + fingerprint + "#" + str(ordinal)).encode()).hexdigest()
            call_id = "callsite:" + stable
            call["map_node_id"] = call_id
            call_node = {"id": call_id, "kind": "callsite", "name": call["written"] + (" [callee truncated]" if call["written_truncated"] else ""), "path": call["path"],
                         "line": call["line"], "sha256": call["sha256"], "fingerprint": fingerprint,
                         "language": caller.get("language"), "evidence": "static", "call_sites": [call],
                         "call_sites_truncated": False, "snippet": call["snippet"], "snippet_truncated": call["snippet_truncated"],
                         "owner_id": caller["id"]}
            nodes.append(call_node)
            node_by_id[call_id] = call_node
            edges.append({"source": caller["id"], "target": call_id, "kind": "contains written call", "evidence": "static",
                          "path": call["path"], "line": call["line"], "snippet": call["snippet"],
                          "snippet_truncated": call["snippet_truncated"], "sha256": call["sha256"]})
            if call["target_id"] and call["target_id"] in node_by_id:
                edges.append({"source": call_id, "target": call["target_id"], "kind": "possible target", "evidence": "inferred",
                              "path": call["path"], "line": call["line"], "snippet": call["snippet"],
                              "snippet_truncated": call["snippet_truncated"], "sha256": call["sha256"], "basis": call["basis"]})
            mapped_calls += 1
    if unmapped_calls:
        warnings.append(f"{unmapped_calls} recorded call sites have no map node due to limits; inspect the containing item for its call-site list.")
    if len(edges) > sl.max_edges:
        edges = edges[:sl.max_edges]
        warnings.append(f"Connection limit reached ({sl.max_edges}).")
    if cover.suppressed:
        warnings.append(f"{cover.suppressed} further per-file notices are not listed here; the coverage summary counts them by reason.")
    if cache is not None:
        cache.touch(cache_keys)
    duplicates = [paths for paths in digests.values() if len(paths) > 1]
    # Inferred links whose two ends lie in different nested Git repositories of the selected folder.
    crossing, crossing_examples, homes = 0, [], {}
    if cover.nested:
        nested_roots = sorted(cover.nested, key=len, reverse=True)

        def home(path):
            if path not in homes:
                homes[path] = next((r for r in nested_roots if path == r or path.startswith(r + "/")), "")
            return homes[path]
        for edge in edges:
            if edge["evidence"] != "inferred" or edge["kind"] not in ("possible call", "possible local module"):
                continue
            source, target = node_by_id.get(edge["source"]), node_by_id.get(edge["target"])
            if source and target and source.get("path") and target.get("path") and home(source["path"]) != home(target["path"]):
                crossing += 1
                if len(crossing_examples) < MAX_EXAMPLES:
                    crossing_examples.append(f"{source['path']}:{edge.get('line')} -> {target['path']} ({edge['kind']})")
    inventory = sorted((n["path"], n["sha256"]) for n in nodes if n["kind"] == "file" and n["sha256"])
    nodes[0]["fingerprint"] = hashlib.sha256(json.dumps([inventory, warnings], ensure_ascii=True, separators=(",", ":")).encode()).hexdigest()
    finished = time.monotonic()
    coverage = {
        "supported_files_found": found_total, "supported_files_found_is_lower_bound": not walk_complete,
        "files_parsed": len(files), "files_listed_without_parsing": sum(cover.failed.values()) if sl.list_unparsed_files else 0,
        "files_not_inspected_due_to_file_limit": max(0, found_total - len(candidates)),
        "by_language": {language: {"found": cover.found[language], "parsed": cover.parsed[language],
                                   "partial": cover.partial[language], "not_parsed": cover.failed[language]}
                        for language in sorted(cover.found)},
        "skipped": cover.skipped,
        "unsupported_extensions": dict(cover.unsupported.most_common(25)),
        "unsupported_files": sum(cover.unsupported.values()),
        "top_level": [{"name": name, "found": found, "inspected": seen} for name, (found, seen) in sorted(cover.top.items())],
        "nested_repositories": cover.nested,
        "cross_repository": {"links": crossing, "examples": crossing_examples},
        "duplicate_content": {"groups": len(duplicates), "files": sum(len(paths) for paths in duplicates),
                              "examples": [paths[:4] for paths in duplicates[:MAX_EXAMPLES]]},
        "cache": {"reused": sum(bool(r.get("from_cache")) for r in records), "parsed_now": sum(r["status"] == "parsed" and not r.get("from_cache") for r in records)},
        "limits": {"files": sl.max_files, "items": sl.max_nodes, "directories": sl.max_directories,
                   "file_bytes": sl.max_file_bytes, "connections": sl.max_edges},
        "seconds": {"walk": round(walked - started, 2), "read_and_parse": round(inspected - walked, 2),
                    "link": round(finished - inspected, 2), "total": round(finished - started, 2)},
    }
    return {"repo_id": repo_id, "root_name": root.name, "nodes": nodes, "edges": edges,
            "files_inspected": len(files), "warnings": warnings, "coverage": coverage,
            "scope": SCOPE, "parser_isolation": limits.isolation}


def parse_python(data: bytes, path: str) -> dict:
    """Runs only inside the existing bounded extraction worker."""
    try:
        text = data.decode("utf-8-sig")
        tree = ast.parse(text, filename=path)
        visitor = _Visitor(path, text, hashlib.sha256(data).hexdigest())
        visitor.visit(tree)
        return {"nodes": visitor.nodes, "edges": visitor.edges, "imports": visitor.imports,
                "calls": visitor.calls, "top_level": visitor.top_level, "members": visitor.members,
                "truncated": visitor.truncated}
    except SyntaxError as exc:
        where = f" near line {exc.lineno}" if isinstance(exc.lineno, int) else ""
        return {"error": "Python syntax this parser does not accept" + where}
    except (UnicodeError, ValueError, RecursionError, MemoryError):
        return {"error": "invalid or overly complex Python source"}


class _Returns(ast.NodeVisitor):
    def __init__(self):
        self.lines = []
        self.features = []

    def generic_visit(self, node):
        kinds = {ast.If: "conditional", ast.For: "loop", ast.AsyncFor: "loop", ast.While: "loop",
                 ast.Try: "exception handling", ast.TryStar: "exception handling", ast.Raise: "raise",
                 ast.Await: "await", ast.Match: "pattern match"}
        kind = kinds.get(type(node))
        if kind:
            self.features.append({"kind": kind, "line": node.lineno})
        super().generic_visit(node)

    def visit_Return(self, node):
        self.lines.append(node.lineno)
        self.generic_visit(node)

    def visit_FunctionDef(self, node):
        pass

    visit_AsyncFunctionDef = visit_FunctionDef
    visit_ClassDef = visit_FunctionDef
    visit_Lambda = visit_FunctionDef


_SIGNATURE_KEEPING_DECORATORS = {"staticmethod", "classmethod", "abstractmethod", "override", "final", "overload"}


def _python_arity(node, is_method):
    """Written-argument counts the signature accepts, or None when a decorator may have changed it."""
    names = {(d.attr if isinstance(d, ast.Attribute) else d.id if isinstance(d, ast.Name) else None) for d in node.decorator_list}
    if not names <= _SIGNATURE_KEEPING_DECORATORS:
        return None
    args = node.args
    positional = len(args.posonlyargs) + len(args.args)
    required = positional - len(args.defaults) + sum(default is None for default in args.kw_defaults)
    maximum = None if args.vararg or args.kwarg else positional + len(args.kwonlyargs)
    if is_method and "staticmethod" not in names and positional:
        # self or cls is supplied by the call syntax, not written as an argument
        required -= int(positional > len(args.defaults))
        maximum = None if maximum is None else maximum - 1
    return {"min": max(required, 0), "max": maximum, "self": False}


class _Locals(ast.NodeVisitor):
    """Names bound in one function body (nested bodies excluded), split into values and nested functions."""

    def __init__(self):
        self.values, self.functions, self.released = set(), {}, set()

    def bind(self, target):
        for item in ast.walk(target):
            if isinstance(item, ast.Name):
                self.values.add(item.id)

    def visit_FunctionDef(self, node):
        self.functions[node.name] = self.functions.get(node.name, 0) + 1

    visit_AsyncFunctionDef = visit_FunctionDef

    def visit_ClassDef(self, node):
        self.values.add(node.name)

    def visit_Lambda(self, node):
        pass

    def visit_ListComp(self, node):
        pass  # comprehension variables live in their own scope

    visit_SetComp = visit_DictComp = visit_GeneratorExp = visit_ListComp

    def visit_Assign(self, node):
        for target in node.targets:
            self.bind(target)
        self.generic_visit(node)

    def visit_AnnAssign(self, node):
        self.bind(node.target); self.generic_visit(node)

    visit_AugAssign = visit_AnnAssign

    def visit_NamedExpr(self, node):
        self.bind(node.target); self.generic_visit(node)

    def visit_For(self, node):
        self.bind(node.target); self.generic_visit(node)

    visit_AsyncFor = visit_For

    def visit_With(self, node):
        for item in node.items:
            if item.optional_vars is not None:
                self.bind(item.optional_vars)
        self.generic_visit(node)

    visit_AsyncWith = visit_With

    def visit_ExceptHandler(self, node):
        if node.name:
            self.values.add(node.name)
        self.generic_visit(node)

    def visit_MatchAs(self, node):
        if node.name:
            self.values.add(node.name)
        self.generic_visit(node)

    def visit_Global(self, node):
        self.released.update(node.names)

    visit_Nonlocal = visit_Global


def _python_locals(node):
    found = _Locals()
    arguments = node.args
    for argument in (*arguments.posonlyargs, *arguments.args, *arguments.kwonlyargs, arguments.vararg, arguments.kwarg):
        if argument is not None:
            found.values.add(argument.arg)
    for statement in node.body:
        found.visit(statement)
    functions = {name for name, count in found.functions.items() if count == 1 and name not in found.values} - found.released
    return (found.values | set(found.functions)) - functions - found.released, functions


def _python_shape(node, lines, is_method=False):
    from .repository_learning import evidence_lines
    args = node.args
    entries = [(a, "positional-only") for a in args.posonlyargs]
    entries += [(a, "positional-or-keyword") for a in args.args]
    if args.vararg:
        entries.append((args.vararg, "variadic positional"))
    entries += [(a, "keyword-only") for a in args.kwonlyargs]
    if args.kwarg:
        entries.append((args.kwarg, "variadic keyword"))
    returns = _Returns()
    for statement in node.body:
        returns.visit(statement)
    return {"parameters": [{"name": a.arg, "kind": kind, "line": a.lineno} for a, kind in entries[:30]],
            "parameters_truncated": len(entries) > 30, "parameter_detail": "named",
            "async": isinstance(node, ast.AsyncFunctionDef), "return_lines": returns.lines[:30],
            "returns_truncated": len(returns.lines) > 30, "return_detail": "explicit", "arity": _python_arity(node, is_method),
            "features": returns.features[:30], "features_truncated": len(returns.features) > 30,
            "evidence_lines": evidence_lines(lines, [a.lineno for a, _ in entries[:30]] + returns.lines[:30] + [f["line"] for f in returns.features[:30]])}


class _Visitor(ast.NodeVisitor):
    def __init__(self, path, text, digest):
        self.path, self.text, self.lines, self.digest = path, text, text.splitlines(), digest
        self.byte_lines = [line.encode("utf-8") for line in self.lines]
        self.file_id = "file:" + path
        self.nodes, self.edges, self.calls, self.imports = [], [], [], []
        self.top_level, self.names, self.stack = defaultdict(list), {}, []
        self.members = {}
        self.local_scopes = []
        self.truncated = False

    def _enclosing_class(self):
        """Qualified name of the class whose method body is being read, if any."""
        for index in range(len(self.stack) - 2, -1, -1):
            if self.stack[index][1] is None:
                return ".".join(entry[0] for entry in self.stack[:index + 1])
        return None

    def _line(self, line):
        return self.lines[line - 1][:1000] if 0 < line <= len(self.lines) else ""

    def visit_ClassDef(self, node):
        self.stack.append((node.name, None))
        self.generic_visit(node)
        self.stack.pop()

    def visit_FunctionDef(self, node):
        if len(self.nodes) >= MAX_FILE_NODES:
            self.truncated = True
            return
        qual = ".".join([x[0] for x in self.stack] + [node.name])
        key = "function:" + self.path + ":" + qual
        self.names[key] = self.names.get(key, 0) + 1
        if self.names[key] > 1:
            key += "#" + str(self.names[key])
        parent = next((x[1] for x in reversed(self.stack) if x[1]), self.file_id)
        fingerprint = hashlib.sha256(ast.dump(node, include_attributes=False).encode()).hexdigest()
        snippet = "\n".join(self._line(i) for i in range(node.lineno, min(node.end_lineno or node.lineno, node.lineno + 11) + 1))
        self.nodes.append({"id": key, "kind": "function", "name": qual, "path": self.path,
                           "line": node.lineno, "end_line": node.end_lineno, "snippet": snippet,
                           "sha256": self.digest, "fingerprint": fingerprint, "language": "python",
                           "shape": _python_shape(node, self.lines, bool(self.stack) and self.stack[-1][1] is None), "evidence": "static"})
        self.edges.append({"source": parent, "target": key, "kind": "defines", "evidence": "static", "path": self.path, "line": node.lineno})
        if not self.stack:
            self.top_level[node.name].append(key)
        elif self.stack[-1][1] is None:
            owner = ".".join(entry[0] for entry in self.stack)
            self.members.setdefault(owner, {}).setdefault(node.name, []).append(key)
        self.stack.append((node.name, key))
        values, functions = _python_locals(node)
        self.local_scopes.append((values, functions, ".".join(entry[0] for entry in self.stack)))
        for child in node.body:
            self.visit(child)
        self.local_scopes.pop()
        self.stack.pop()

    visit_AsyncFunctionDef = visit_FunctionDef

    def _written_callee(self, node):
        start = node.lineno - 1
        end = (getattr(node, "end_lineno", None) or node.lineno) - 1
        end_col = getattr(node, "end_col_offset", None)
        chunks, size, incomplete = [], 0, False
        for index in range(start, min(end + 1, len(self.byte_lines))):
            line = self.byte_lines[index]
            left = node.col_offset if index == start else 0
            right = end_col if index == end and end_col is not None else len(line)
            piece = line[left:right]
            remaining = 804 - size
            if remaining <= 0:
                incomplete = True
                break
            if len(piece) > remaining:
                piece, incomplete = piece[:remaining], True
            chunks.append(piece)
            size += len(piece)
            if incomplete:
                break
        value = b"\n".join(chunks).decode("utf-8", errors="ignore") or "[complex call]"
        return value[:200], incomplete or len(value) > 200

    def visit_Call(self, node):
        base, attribute = None, None
        if isinstance(node.func, ast.Name):
            base = node.func.id
        elif isinstance(node.func, ast.Attribute) and isinstance(node.func.value, ast.Name):
            base, attribute = node.func.value.id, node.func.attr
        if len(self.calls) < MAX_FILE_CALLS:
            caller = next((x[1] for x in reversed(self.stack) if x[1]), self.file_id)
            written, written_truncated = self._written_callee(node.func)
            record = {"caller": caller, "base": base, "attribute": attribute, "written": written, "written_truncated": written_truncated,
                      "written_arguments": len(node.args) + len(node.keywords),
                      "line": node.lineno, "snippet": self._line(node.lineno),
                      "snippet_truncated": len(self.lines[node.lineno - 1]) > 1000,
                      "line_sha256": hashlib.sha256(self.byte_lines[node.lineno - 1]).hexdigest()}
            if base in ("self", "cls") and attribute:
                owner = self._enclosing_class()
                if owner:
                    record["member"], record["member_of"] = attribute, owner
            if base and not attribute:
                # Python scoping is lexical: a name bound in an enclosing function is that binding, not the module's.
                for values, functions, prefix in reversed(self.local_scopes):
                    if base in functions:
                        record["local_target"] = "function:" + self.path + ":" + prefix + "." + base
                        break
                    if base in values:
                        record["local"] = True
                        break
            if any(isinstance(item, ast.Starred) for item in node.args) or any(keyword.arg is None for keyword in node.keywords):
                record["expands"] = True  # *args or **kwargs: the number of values passed is not visible
            self.calls.append(record)
        else:
            self.truncated = True
        self.generic_visit(node)

    def visit_Import(self, node):
        for alias in node.names:
            self._import(alias.name, 0, None, alias.asname or alias.name.split(".")[0], bool(alias.asname), node.lineno)

    def visit_ImportFrom(self, node):
        for alias in node.names:
            self._import(node.module or "", node.level, alias.name, None if alias.name == "*" else alias.asname or alias.name,
                         bool(alias.asname), node.lineno)

    def _import(self, module, level, symbol, bound, aliased, line):
        if len(self.nodes) >= MAX_FILE_NODES:
            self.truncated = True
            return
        name = "." * level + module + ((" import " + symbol) if symbol else "")
        key = f"import:{self.path}:{line}:{name}"
        self.names[key] = self.names.get(key, 0) + 1
        if self.names[key] > 1:
            key += "#" + str(self.names[key])
        self.nodes.append({"id": key, "kind": "dependency", "name": name, "path": self.path,
                           "line": line, "sha256": self.digest, "evidence": "static"})
        self.edges.append({"source": self.file_id, "target": key, "kind": "imports", "evidence": "static", "path": self.path, "line": line})
        self.imports.append({"id": key, "module": module, "level": level, "symbol": symbol, "bound": bound,
                             "aliased": aliased, "line": line, "snippet": self._line(line)})
