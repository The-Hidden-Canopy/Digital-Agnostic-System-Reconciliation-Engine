"""Read-only, bounded repository map. Repository code is never imported or run.

Two kinds of statement leave this module and they are never mixed:
  static   - syntax that is written in a scanned file (a definition, an import, a call expression);
  inferred - a candidate target chosen by a stated naming rule, carried with that rule as its basis.
Nothing here observes execution.
"""
